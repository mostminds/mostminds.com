// ---- shorthands ----
const W = (name, tier, count, model, arts, note) => ({ name, note, tier, count, model, arts });
const B = (name, form, look, parts, note, abilities) => ({ name, note, form, look, parts, abilities });
const A = (kind, name, note, p = {}) => ({ kind, name, note, ...p });
const pal = (P) => ({ skin: P.skin, cloth: P.cloth, cloth2: P.cloth2, armor: P.armor, trim: P.trim });
/** a rider of the realm (its own species and palette) on a flying mount */
const rider = (P, outfit, mountType, weapon, mount, x = {}) => ({ body: 'rider', species: P.species, ...pal(P), outfit, mountType, weapon, mount, ...x });
/** a machine or conveyance in the realm's colours */
const craft = (P, kind, style, x = {}) => ({ body: 'aircraft', kind, style, cloth: P.cloth, cloth2: P.cloth2, armor: P.armor, trim: P.trim, ...x });
/** a great flying beast, riderless or carrying its crew */
const flier = (kind, mount, x = {}) => ({ body: 'flier', kind, mount, skin: mount, ...x });
const dragon = (scales, scale, x = {}) => ({ body: 'dragon', scales, scale, ...x });

