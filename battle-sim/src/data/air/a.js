// ---- model and entry shorthands (P is the faction palette, as in realms.js) ----
const pal = (P) => ({ species: P.species, skin: P.skin, cloth: P.cloth, cloth2: P.cloth2, armor: P.armor, trim: P.trim });
const rider = (P, outfit, mountType, weapon, mount, x = {}) => ({ body: 'rider', ...pal(P), outfit, mountType, weapon, mount, ...x });
const craft = (P, kind, style, x = {}) => ({ body: 'aircraft', kind, style, cloth: P.cloth, cloth2: P.cloth2, armor: P.armor, trim: P.trim, ...x });
const beast = (kind, skin, x = {}) => ({ body: 'flier', kind, skin, mount: skin, ...x });
const dragon = (scales, x = {}) => ({ body: 'dragon', kind: 'dragon', scales, skin: scales, mount: scales, ...x });
const air = (name, tier, count, model, arts, note) => ({ name, note, tier, count, model, arts });
const ab = (kind, name, params, note) => ({ kind, name, note, ...params });

